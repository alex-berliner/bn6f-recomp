#!/usr/bin/env python3
"""Find register-level code in the port's hand-written C (docs/C_CALLING_CONVENTION.md §3.8).

  tools/abi/lint.py [PATH...]                       JSON report on stdout, summary on stderr
  tools/abi/lint.py --check [--baseline FILE]       fail (exit 1) only on violations the baseline lacks
  tools/abi/lint.py --write-baseline FILE           record today's violations as accepted

PATHs are .c files or directories of them (default cport/src/game). Generated
files (first lines say "Generated by", or abi_thunks.c) are skipped.

What counts as register-level, per category (comments and string literals are ignored):
  regs        R0..R12                    sp/lr    SP, LR
  flags       SET_FLAGS_*, ZERO_FLAG() and the other flag reads
  cpu         any cpu.X access (cpu.ret, cpu.nz, ...)
  guest_call  GUEST_CALL, GUEST_CALL_ADDR, run(), dispatch(), jump_to(), swi_call()
  next_call   a direct call of a `Next` function, e.g. `return f();` (names from this code, and from
              cport/include/lifted.h once a lift has generated it)
  return      RETURN_TO_CALLER, RETURN_TO, DONE (how a register body returns to its guest caller)
LD*/ST* memory macros and GUEST_PTR are not register-level (struct access replaces them later).

Each hit belongs to its enclosing function, of one of these kinds:
  typed       an ordinary C function: any hit is a violation of the target convention
  next        returns `Next` (a `Next NAME(void)` body or a Next helper): a register body to retire
  adapter     a thin `Next` adapter: no guest_call/next_call, no LD/ST, no control flow, at most 8
              statements, and it calls a typed function defined in the scanned code. Its register use
              is its job (arguments in, results and flags out): allowed, not a violation.
  file        file scope (e.g. a #define using R0)
A `/* register form: <why> */` comment inside a function, or in the comment block right
before it, makes it an exception: reported with its reason, not counted as a violation.

The baseline (tools/abi/lint_baseline.json) holds per-function category counts, keyed by
function name (file:name for static functions), so line shifts and moves between files do
not matter. --check fails on a function the baseline lacks or a category count above it;
counts below it are improvements (re-write the baseline to lock them in).
"""
from __future__ import annotations

import argparse
import bisect
import json
import os
import re
import sys
from dataclasses import dataclass, field
from typing import Any

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_PATHS = [os.path.join(ROOT, "cport/src/game")]
DEFAULT_BASELINE = os.path.join(ROOT, "tools/abi/lint_baseline.json")
LIFTED_H = os.path.join(ROOT, "cport/include/lifted.h")

CATEGORIES: dict[str, re.Pattern[str]] = {
    "regs": re.compile(r"\bR(?:1[0-2]|[0-9])\b"),
    "sp": re.compile(r"\bSP\b"),
    "lr": re.compile(r"\bLR\b"),
    "flags": re.compile(r"\bSET_FLAGS_\w+|\b(?:ZERO|NEGATIVE|CARRY|OVERFLOW)_FLAG\b"),
    "cpu": re.compile(r"\bcpu\s*\.\s*\w+"),
    "guest_call": re.compile(r"\bGUEST_CALL(?:_ADDR)?\b|\b(?:run|dispatch|jump_to|swi_call)\s*\("),
    "return": re.compile(r"\bRETURN_TO_CALLER\b|\bRETURN_TO\b|\bDONE\b"),
}
CALL_RE = re.compile(r"\b([A-Za-z_]\w*)\s*\(")
MEMORY_RE = re.compile(r"\b(?:LD|LDS|ST)(?:8|16|32)\s*\(")
CONTROL_RE = re.compile(r"\b(?:if|for|while|switch|goto)\b|\?")
EXCEPTION_RE = re.compile(r"register form:\s*(.*?)\s*(?:\*/)?$", re.I | re.S)
GENERATED_RE = re.compile(r"Generated by|@generated|DO NOT EDIT")
NEXT_PROTO_RE = re.compile(r"^Next\s+(\w+)\s*\(\s*void\s*\)\s*;", re.M)


@dataclass
class Function:
    name: str
    kind: str                     # typed | next | adapter | file
    file: str
    line: int
    static: bool = False
    body: tuple[int, int] = (0, 0)          # offsets of its { and }
    text: str = ""                          # the body, comments and strings blanked
    body_line: int = 0
    hits: dict[str, list[int]] = field(default_factory=dict)
    exception: str | None = None

    @property
    def key(self) -> str:
        return f"{self.file}:{self.name}" if self.static or self.kind == "file" else self.name

    def counts(self) -> dict[str, int]:
        return {c: len(v) for c, v in sorted(self.hits.items()) if v}

    def violates(self) -> bool:
        return bool(self.hits) and self.exception is None and self.kind != "adapter"


def strip(text: str) -> tuple[str, list[tuple[int, int, str]]]:
    """Text with comments and string/char literal contents blanked (offsets and newlines
    kept), and the comments as (start, end, text)."""
    out = list(text)
    comments: list[tuple[int, int, str]] = []

    def blank(a: int, b: int) -> None:
        for k in range(a, b):
            if out[k] != "\n":
                out[k] = " "

    i, n = 0, len(text)
    while i < n:
        if text.startswith("/*", i) or text.startswith("//", i):
            end = text.find("*/", i + 2) + 2 if text[i + 1] == "*" else text.find("\n", i)
            end = n if end < i else end      # unterminated: to the end
            comments.append((i, end, text[i:end]))
            blank(i, end)
            i = end
        elif text[i] in "\"'":
            j = i + 1
            while j < n and text[j] not in (text[i], "\n"):
                j += 2 if text[j] == "\\" else 1
            blank(i + 1, min(j, n))
            i = j + 1
        else:
            i += 1
    return "".join(out), comments


def blank_preprocessor(code: str) -> str:
    """Preprocessor lines (with continuations) blanked, for brace matching."""
    lines = code.split("\n")
    cont = False
    for k, ln in enumerate(lines):
        if cont or ln.lstrip().startswith("#"):
            cont = ln.rstrip().endswith("\\")
            lines[k] = " " * len(ln)
    return "\n".join(lines)


def header_function(header: str) -> tuple[str, str, bool] | None:
    """(name, return type text, static) when the text before a top-level `{` is a function header."""
    h = header.strip()
    h = re.sub(r"__attribute__\s*\(\(.*?\)\)\s*$", "", h, flags=re.S).strip()
    if not h.endswith(")") or "=" in h:
        return None
    depth = 0
    for k in range(len(h) - 1, -1, -1):
        depth += {")": 1, "(": -1}.get(h[k], 0)
        if depth == 0:
            break
    else:
        return None
    m = re.search(r"([A-Za-z_]\w*)\s*$", h[:k])
    if not m or m.group(1) in ("if", "while", "for", "switch", "return", "sizeof"):
        return None
    ret = h[:m.start()]
    if not ret.strip():
        return None
    return m.group(1), ret, bool(re.search(r"\bstatic\b", ret))


def scan_file(name: str, text: str) -> list[Function]:
    """Functions of one file with their register-level hits (file scope as a pseudo-function)."""
    code, comments = strip(text)
    braces = blank_preprocessor(code)
    nl = [k for k, ch in enumerate(text) if ch == "\n"]

    def line_of(off: int) -> int:
        return bisect.bisect_left(nl, off) + 1

    funcs: list[Function] = []
    depth, top_end, open_at = 0, 0, 0
    for k, ch in enumerate(braces):
        if ch == "{":
            if depth == 0:
                open_at = k
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                header = braces[top_end:open_at]
                hdr = header_function(header)
                if hdr:
                    fname, ret, static = hdr
                    start = top_end + len(header) - len(header.lstrip())
                    kind = "next" if re.search(r"\bNext\b", ret) else "typed"
                    funcs.append(Function(fname, kind, name, line_of(start), static, (open_at, k),
                                          code[open_at:k + 1], line_of(open_at)))
                    # a register-form comment inside it, or in the comments right before its header
                    for c0, c1, ctext in comments:
                        m = EXCEPTION_RE.search(ctext)
                        if m and (open_at <= c0 <= k or top_end <= c0 and c1 <= start):
                            funcs[-1].exception = " ".join(m.group(1).replace("*", " ").split()) or "?"
                top_end = k + 1
        elif ch == ";" and depth == 0:
            top_end = k + 1
    file_scope = Function("<file scope>", "file", name, 1)
    starts = [f.body[0] for f in funcs]
    for cat, rx in CATEGORIES.items():
        for m in rx.finditer(code):
            j = bisect.bisect_right(starts, m.start()) - 1
            f = funcs[j] if j >= 0 and m.start() <= funcs[j].body[1] else file_scope
            f.hits.setdefault(cat, []).append(line_of(m.start()))
    return funcs + [file_scope]


def mark_calls(funcs: list[Function], next_names: set[str]) -> None:
    """next_call hits, and the Next functions that are only thin adapters of a typed function."""
    typed = {f.name for f in funcs if f.kind == "typed"}
    for f in funcs:
        if f.kind == "file":
            continue
        calls = [(m.group(1), m.start()) for m in CALL_RE.finditer(f.text)]
        for callee, off in calls:
            if callee in next_names and callee != f.name:
                f.hits.setdefault("next_call", []).append(f.body_line + f.text[:off].count("\n"))
        if (f.kind == "next" and "guest_call" not in f.hits and "next_call" not in f.hits
                and not MEMORY_RE.search(f.text) and not CONTROL_RE.search(f.text) and f.text.count(";") <= 8
                and any(callee in typed for callee, _ in calls)):
            f.kind = "adapter"


def lint(paths: list[str]) -> list[Function]:
    """Every function (and file scope) of the hand-written C under PATHS."""
    files: list[str] = []
    for p in paths:
        if os.path.isdir(p):
            files += [os.path.join(p, f) for f in sorted(os.listdir(p)) if f.endswith(".c")]
        else:
            files.append(p)
    next_names: set[str] = set()
    if os.path.exists(LIFTED_H):
        next_names |= set(NEXT_PROTO_RE.findall(open(LIFTED_H).read()))
    funcs: list[Function] = []
    for path in files:
        text = open(path).read()
        name = os.path.basename(path)
        if name == "abi_thunks.c" or GENERATED_RE.search("\n".join(text.split("\n")[:3])):
            continue
        funcs += scan_file(name, text)
    next_names |= {f.name for f in funcs if f.kind == "next"}
    mark_calls(funcs, next_names)
    return funcs


def report(funcs: list[Function]) -> dict[str, object]:
    """The JSON report: totals, then per file the functions with hits or an exception."""
    real = [f for f in funcs if f.kind != "file"]
    bad = [f for f in funcs if f.violates()]
    per_cat: dict[str, int] = {}
    for f in bad:
        for c, n in f.counts().items():
            per_cat[c] = per_cat.get(c, 0) + n
    totals = {
        "files": len({f.file for f in funcs}),
        "functions": len(real),
        "by_kind": {k: sum(f.kind == k for f in real) for k in ("typed", "next", "adapter")},
        "violating_functions": {k: sum(f.kind == k for f in bad) for k in ("typed", "next", "file")},
        "violation_hits": dict(sorted(per_cat.items())),
        "exceptions": sum(f.exception is not None for f in funcs),
    }
    files: dict[str, list[dict[str, object]]] = {}
    for f in funcs:
        if f.hits or f.exception:
            files.setdefault(f.file, []).append({
                "name": f.name, "kind": f.kind, "line": f.line, "static": f.static,
                "counts": f.counts(), "lines": {c: v for c, v in sorted(f.hits.items())},
                "exception": f.exception, "violation": f.violates()})
    return {"totals": totals, "files": files}


def baseline_of(funcs: list[Function]) -> dict[str, dict[str, int]]:
    return {f.key: f.counts() for f in sorted(funcs, key=lambda f: f.key) if f.violates()}


def check(funcs: list[Function], baseline: dict[str, dict[str, int]]) -> tuple[list[Any], list[Any]]:
    """New violations (not in the baseline, or above its counts) and improvements."""
    new: list[Any] = []
    improved: list[Any] = []
    now = baseline_of(funcs)
    where = {f.key: f for f in funcs}
    for key, counts in now.items():
        base = baseline.get(key, {})
        more = {c: n - base.get(c, 0) for c, n in counts.items() if n > base.get(c, 0)}
        if more:
            f = where[key]
            new.append({"function": key, "file": f.file, "line": f.line, "kind": f.kind,
                        "new_hits": more, "lines": {c: f.hits[c] for c in more},
                        "in_baseline": key in baseline})
    for key, base in baseline.items():
        counts = now.get(key, {})
        fewer = {c: n - counts.get(c, 0) for c, n in base.items() if counts.get(c, 0) < n}
        if fewer:
            improved.append({"function": key, "fewer_hits": fewer, "clean": key not in now})
    return new, improved


def summary(rep: dict[str, object]) -> str:
    t = rep["totals"]
    assert isinstance(t, dict)
    kinds = ", ".join(f"{n} {k}" for k, n in t["by_kind"].items())
    viol = ", ".join(f"{n} {k}" for k, n in t["violating_functions"].items() if n)
    hits = ", ".join(f"{c} {n}" for c, n in t["violation_hits"].items())
    return (f"lint: {t['files']} files, {t['functions']} functions ({kinds})\n"
            f"  with register-level code: {viol or 'none'}\n"
            f"  hits: {hits or 'none'}\n"
            f"  register-form exceptions: {t['exceptions']}")


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("paths", nargs="*", default=DEFAULT_PATHS, help=".c files or directories")
    ap.add_argument("--check", action="store_true", help="exit 1 on violations the baseline lacks")
    ap.add_argument("--baseline", default=DEFAULT_BASELINE)
    ap.add_argument("--write-baseline", metavar="FILE", help="record the current violations as accepted")
    ap.add_argument("--quiet", action="store_true", help="no summary on stderr")
    args = ap.parse_args()
    funcs = lint(args.paths)
    rep = report(funcs)
    if not args.quiet:
        print(summary(rep), file=sys.stderr)
    if args.write_baseline:
        base = baseline_of(funcs)
        rows = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in base.items())   # one line each
        with open(args.write_baseline, "w") as fh:
            fh.write('{\n "comment": "tools/abi/lint.py --write-baseline: register-level code accepted '
                     'today, per function (category counts)",\n "functions": {\n' + rows + "\n }\n}\n")
        print(f"wrote {args.write_baseline}: {len(base)} functions", file=sys.stderr)
        return 0
    if args.check:
        with open(args.baseline) as fh:
            new, improved = check(funcs, json.load(fh)["functions"])
        json.dump({"ok": not new, "new": new, "improved": improved}, sys.stdout, indent=1)
        print()
        for n in new:
            lines = sorted({ln for v in n["lines"].values() for ln in v})
            print(f"NEW {n['file']}:{lines[0]} {n['function']} ({n['kind']}): "
                  + ", ".join(f"{c} +{k}" for c, k in n["new_hits"].items()), file=sys.stderr)
        if improved:
            print(f"{len(improved)} functions have less register-level code than the baseline: "
                  f"tools/abi/lint.py --write-baseline {args.baseline}", file=sys.stderr)
        print("lint check: " + (f"{len(new)} functions with new register-level code" if new else "ok"),
              file=sys.stderr)
        return 1 if new else 0
    json.dump(rep, sys.stdout, indent=1)
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""The jump tables readable functions dispatch through on a selector byte, for the difftest's inputs.

  tools/abi/jump_tables.py        write cport/host/jump_tables.h (and say how many)

A readable function whose original does

    ldr  rT, off_X        // =TABLE
    ldrb rS, [rB, #OFF]
    ldr  rT, [rT, rS]
    mov  lr, pc
    bx   rT

jumps through word OFF of TABLE. The game only stores selectors the table has (0, 4, ...); a random
byte indexes past it, where the original jumps through whatever word follows (now and then code, so
it returns), and readable C that switches on the table's values does nothing. Those inputs are out of
the domain the port is held to, so the difftest gives such functions (cport/host/difftest_gen.c) a work
area in EWRAM for rB and a selector the table has: one JT(name, B, OFF, entries) line each.
Rerun after installs; the commit gate does not check it.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import funcindex  # noqa: E402

OUT = os.path.join(ROOT, "cport/host/jump_tables.h")


def constants() -> dict[str, int]:
    out: dict[str, int] = {}
    for h in glob.glob(os.path.join(ROOT, "cport/include/*.h")):
        for m in re.finditer(r"^#define (\w+) (0x[0-9A-Fa-f]+|\d+)u?\b", open(h, errors="replace").read(), re.M):
            out.setdefault(m[1], int(m[2], 0))
    return out


def table_size(lines: list[str], label: str) -> int:
    """The words after LABEL: in its source file (every `.word` line up to the next other line)."""
    for i, line in enumerate(lines):
        if line.startswith(label + ":"):
            n = 0
            for word in lines[i + 1:]:
                if re.match(r"\s*\.word\b", word):
                    n += len(word.split(",")) if "," in word else 1
                elif word.strip() and not word.strip().startswith("//"):
                    break
            return n
    return 0


def scan() -> list[tuple[str, int, int, int]]:
    readable = funcindex.readable_functions()
    eq = constants()
    found: list[tuple[str, int, int, int]] = []
    for path in sorted(glob.glob(os.path.join(ROOT, "bn6f/asm/*.s"))):
        lines = open(path, errors="replace").read().split("\n")
        for i, line in enumerate(lines):
            m = re.match(r"^(\w+):", line)
            if not m or m[1] not in readable:
                continue
            body = []
            for line2 in lines[i + 1:i + 300]:
                if re.match(r"\s*(thumb|arm)_func_end", line2):
                    break
                body.append(line2)
            code = [re.sub(r"//.*", "", x).strip() for x in body]
            for k, c in enumerate(code):
                m1 = re.match(r"ldrb (r\d+), \[(r\d+), ?#(\w+)\]$", c)
                if not m1:
                    continue
                for j in (k + 1, k + 2):
                    if j + 2 >= len(code):
                        continue
                    m2 = re.match(r"ldr (r\d+), \[(r\d+), ?(r\d+)\]$", code[j])
                    if not (m2 and m1[1] in (m2[2], m2[3]) and code[j + 1] == "mov lr, pc"
                            and code[j + 2] == f"bx {m2[1]}"):
                        continue
                    label = None
                    for prev in body[:k + 1][::-1]:
                        mm = re.search(r"ldr (r\d+), \w+ // =(\w+)", prev)
                        if mm and mm[1] in (m2[1], m2[2], m2[3]):
                            label = mm[2]
                            break
                    off = m1[3]
                    value = int(off, 0) if re.fullmatch(r"(0x[0-9a-fA-F]+|\d+)", off) else eq.get(off)
                    n = table_size(lines, label) if label else 0
                    if value is not None and n > 0 and value < 0x100:
                        found.append((m[1], int(m1[2][1:]), value, n))
                    break
    return sorted(set(found))


def main() -> None:
    rows = scan()
    with open(OUT, "w") as fh:
        fh.write("/* Generated by tools/abi/jump_tables.py: readable functions that jump through a table on a\n"
                 " * selector byte, JT(name, base register, selector offset, table entries). */\n")
        for name, base, off, n in rows:
            fh.write(f"JT({name}, {base}, {off:#x}, {n})\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(rows)} functions")


if __name__ == "__main__":
    main()

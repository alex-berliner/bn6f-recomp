#!/usr/bin/env python3
"""Write the symbol database's findings into the disassembly as comments.

  tools/symdoc.py [--commit] [--no-build]

For every symbols/db entry, a comment block goes right above the symbol's
definition in bn6f (before its thumb_func_start/arm_func_start/thumb_local_start
line for functions, above its label otherwise):

    // symdb: <summary>
    // symdb: <interface, wrapped>
    // symdb: <status>; evidence and how to reproduce it: recomp symbols/db/NAME.yaml

Existing `// symdb:` lines there are replaced, so running it again updates
the comments. bn6f is rebuilt (the ROM must stay identical; comments do not
change it); with --commit the change is committed in bn6f and recorded in
each entry's changes. --no-build skips the rebuild, for a caller that builds
bn6f right after (the record workflow renames next: one build checks both).
"""
import datetime, glob, os, re, subprocess, sys, textwrap
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BN6F = os.path.join(ROOT, "bn6f")
TAG = "// symdb: "


def definition(name):
    """(file, line index) of NAME's label definition in bn6f sources."""
    pat = re.compile(rf"^\s*{re.escape(name)}::?(\s|$)")
    for p in sorted(glob.glob(os.path.join(BN6F, "**", "*.s"), recursive=True)):
        if "/tools/" in p:
            continue
        for i, line in enumerate(open(p, encoding="utf-8", errors="surrogateescape")):
            if pat.match(line):
                return p, i
    return None, None


def block(e):
    lines = [e["summary"]]
    if e.get("interface"):
        lines += textwrap.wrap(str(e["interface"]), 96)
    lines.append(f"{e['status']}; evidence and how to reproduce it: recomp symbols/db/{e['name']}.yaml")
    return [TAG + l + "\n" for l in lines]


def main():
    entries = [yaml.safe_load(open(p)) for p in sorted(glob.glob(os.path.join(ROOT, "symbols", "db", "*.yaml")))]
    changed = []
    for e in entries:
        path, i = definition(e["name"])
        if path is None:
            print(f"{e['name']}: no definition label found in bn6f; skipped")
            continue
        lines = open(path, encoding="utf-8", errors="surrogateescape").readlines()
        at = i
        while at > 0 and re.match(r"^\s*(thumb_func_start|arm_func_start|thumb_local_start|arm_local_start|\.align|\.balign)\b",
                                  lines[at - 1]):
            at -= 1
        top = at
        while top > 0 and lines[top - 1].startswith(TAG):
            top -= 1
        new = block(e)
        if lines[top:at] != new:
            lines[top:at] = new
            open(path, "w", encoding="utf-8", errors="surrogateescape").writelines(lines)
            changed.append(e["name"])
    print(f"{len(changed)} comment blocks written")
    if not changed:
        return
    if "--no-build" in sys.argv:
        print("bn6f not rebuilt (--no-build)")
    else:
        tc = os.path.join(ROOT, "toolchain", "bin")
        r = subprocess.run(["make", f"-j{os.cpu_count()}"] + [f"{v}={tc}/arm-none-eabi-{t}" for v, t in
                           (("AS", "as"), ("LD", "ld"), ("OBJCOPY", "objcopy"), ("OBJDUMP", "objdump"))],
                           cwd=BN6F, capture_output=True, text=True)
        if r.returncode:
            sys.exit("bn6f build failed or the ROM changed:\n" + (r.stdout + r.stderr)[-2000:])
        print("bn6f rebuilt, ROM identical")
    if "--commit" in sys.argv:
        subprocess.run(["git", "add", "-A"], cwd=BN6F, check=True)
        subprocess.run(["git", "commit", "-q", "-m", "Document symbols from the recomp symbol database (symdb comments)\n\n"
                        + "Generated by the recomp repo's tools/symdoc.py from symbols/db; ROM unchanged.\n"
                        + "\n".join(f"  {n}" for n in changed)], cwd=BN6F, check=True)
        commit = subprocess.run(["git", "log", "-1", "--format=%h"], cwd=BN6F, capture_output=True, text=True).stdout.strip()
        today = datetime.date.today().isoformat()
        for e in entries:
            if e["name"] in changed:
                p = os.path.join(ROOT, "symbols", "db", f"{e['name']}.yaml")
                e.setdefault("changes", []).append({"date": today, "what": "doc comment (symdb block) at the definition",
                                                    "where": f"bn6f {commit}", "tool": "tools/symdoc.py"})
                with open(p, "w") as f:
                    yaml.safe_dump(e, f, sort_keys=False, allow_unicode=True, width=110)
        print(f"bn6f commit {commit}; entries updated")


if __name__ == "__main__":
    main()

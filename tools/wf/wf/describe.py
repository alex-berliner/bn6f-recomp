"""docs/workflows/: each workflow's diagram and a page generated from its
code (what it is for, its steps in order, what each reads, needs and
produces, and its decisions), so the docs cannot disagree with the graphs."""
import inspect
import re
from collections.abc import Sequence
from pathlib import Path

from pydantic import BaseModel

from wf.burr_typed import AnyStepOrPause, Transition, step_models
from wf.registry import WORKFLOWS, WorkflowEntry


def write_docs(out_dir: Path) -> tuple[Path, ...]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for entry in WORKFLOWS:
        entry.graph().draw(out_dir / entry.name)
        page = out_dir / f"{entry.name}.md"
        page.write_text(_page(entry))
        written += [out_dir / f"{entry.name}.png", page]
    index = out_dir / "README.md"
    index.write_text(_index())
    return (*written, index)


def _index() -> str:
    lines = ["# Workflows", "",
             "Generated by `python -m wf docs` from tools/wf; do not edit by hand.", "",
             "| Workflow | Burr UI project | What it is for |", "|---|---|---|"]
    for entry in WORKFLOWS:
        summary = (inspect.getdoc(entry.module) or "").split("\n\n")[0].replace("\n", " ")
        lines.append(f"| [{entry.name}]({entry.name}.md) | {entry.project} | {summary} |")
    return "\n".join(lines) + "\n"


def _page(entry: WorkflowEntry) -> str:
    graph = entry.graph()
    lines = [f"# {entry.name}", "", inspect.getdoc(entry.module) or "", "",
             f"![{entry.name}]({entry.name}.png)", "",
             f"Runs are tracked in the Burr UI under project `{entry.project}`.", "", "## Steps", ""]
    for step in _steps_in_order(graph.first, graph.transitions):
        models = step_models(step)
        kind = "pause point" if models.answer is not None else "step"
        lines += [f"### `{step.__name__}` ({kind})", "", inspect.getdoc(step) or "", "",
                  f"- reads: {_fields(models.input)}"]
        if models.answer is not None:
            lines.append(f"- waits for: `{models.answer.__name__}` ({_fields(models.answer)})")
        lines += [f"- produces: {_fields(models.output)}", f"- then: {_next_steps(step, graph.transitions)}", ""]
    return "\n".join(lines)


def _steps_in_order(first: AnyStepOrPause, transitions: Sequence[Transition]) -> list[AnyStepOrPause]:
    order = [first]
    for transition in transitions:
        for step in (transition.after, transition.go_to):
            if step not in order:
                order.append(step)
    return order


def _next_steps(step: AnyStepOrPause, transitions: Sequence[Transition]) -> str:
    ways = [f"`{transition.go_to.__name__}`" + (f" when `{transition.when.__name__}`" if transition.when else "")
            for transition in transitions if transition.after is step]
    return "; ".join(ways) or "the run ends"


def _fields(model: type[BaseModel]) -> str:
    fields = [f"`{name}: {_type_name(field.annotation)}`" for name, field in model.model_fields.items()]
    return ", ".join(fields) or "nothing"


def _type_name(annotation: object) -> str:
    text = annotation.__name__ if isinstance(annotation, type) else str(annotation)
    return re.sub(r"\b(?:wf|pathlib)(?:\.\w+)*\.(?=[A-Z])", "", text)

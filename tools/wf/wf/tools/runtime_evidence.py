# ── selection: which `wf investigate` entries get runtime evidence ───

def investigate_sources_names() -> frozenset[str]:
    """The names of the symbols/db entries whose `sources` mention `wf investigate` -- the
    task's "from `wf investigate`" filter (the workflow reuses these, never the others)."""
    db = REPO / "symbols/db"
    out: set[str] = set()
    for path in db.glob("*.yaml"):
        try:
            loaded = yaml.safe_load(path.read_text())
        except yaml.YAMLError:
            continue
        if not isinstance(loaded, dict):
            continue
        sources = loaded.get("sources")
        if not isinstance(sources, list):
            continue
        for source in sources:
            if isinstance(source, str) and source.startswith("wf investigate"):
                out.add(path.stem)
                break
    return frozenset(out)


def select_runtime_targets(count: int, only: tuple[FunctionName, ...], states: int,
                          run_dir: Path) -> tuple[FunctionName, ...]:
    """The functions to probe (in source-order newest first), skipping those without captured
    calls and those a prior run already finished.

    - `wf investigate` entries come first
    - newest first within each group (the snapshots' mtime stamps the capture order)
    - skip those with no captured calls (mgba_run has nothing to replay)
    - skip those a previous `wf runtime-evidence` run already wrote evidence for (the per-name
      YAML in build/runtime/*/)
    - if `--only` is given, return exactly those (validated against captured calls)"""
    db = investigate_sources_names()
    eligible: list[tuple[float, FunctionName]] = []
    for name in sorted(db):
        if only and name not in only:
            continue
        snaps = SNAPSHOTS / name
        if not snaps.is_dir():
            continue
        mtime = max((path.stat().st_mtime for path in snaps.glob("*.bin")
                     if not path.name.endswith(".exit.bin")), default=0.0)
        if _already_done(name):
            continue
        eligible.append((mtime, FunctionName(name)))
    eligible.sort(key=lambda row: (-row[0], row[1]))
    if only:
        return tuple(name for _mtime, name in eligible)
    return tuple(name for _mtime, name in eligible[:count])


def _already_done(name: FunctionName) -> bool:
    """A previous `wf runtime-evidence` run wrote an evidence item for this function (its
    NAME.yaml exists under build/runtime/RUN_ID/, and the verdict is one of the valid ones)."""
    for run_dir in (RUNTIME).iterdir() if RUNTIME.exists() else ():
        if not run_dir.is_dir():
            continue
        path = run_dir / f"{name}.yaml"
        if path.exists():
            try:
                header = path.read_text(errors="replace").splitlines()[:6]
            except OSError:
                continue
            if any(line.strip().startswith("verdict:") for line in header):
                return True
    return False


def probe_work_dir(run_dir: Path, name: FunctionName) -> Path:
    """The function's probe subdirectory under run_dir/probe/NAME/."""
    path = run_dir / "probe" / str(name)
    path.mkdir(parents=True, exist_ok=True)
    return path

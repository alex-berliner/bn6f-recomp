def _ram_symbols() -> list[tuple[int, int, str]]:
    """Address ranges of bn6f's RAM data symbols, sorted by start address, [start, end). The
    `elf_symbols` cache is large: this walks the bn6f/bn6f.elf `nm` once and keeps the IWRAM,
    EWRAM, palette, VRAM and SRAM data symbols. Functions and ROM labels are skipped -- the
    function under test writes to RAM, and reading a function's body for a write would mislead."""
    global RAM_SYMBOLS_CACHE
    if RAM_SYMBOLS_CACHE is not None:
        return RAM_SYMBOLS_CACHE
    syms: dict[str, int] = symdb.elf_symbols(symdb.Cache())
    sections = _ram_sections()
    out: list[tuple[int, int, str]] = []
    for name, address in syms.items():
        section = _which_section(address, sections)
        if section is None:
            continue
        if name.startswith(("sub_", "asm", "nullsub_", "dead_", "unused_")):
            continue
        end = _symbol_end(name, address, syms)
        if end is None or end <= address:
            continue
        out.append((address, end, name))
    out.sort(key=lambda row: (row[0], -((row[1] - row[0]))))
    RAM_SYMBOLS_CACHE = out
    return out


def _ram_sections() -> tuple[tuple[int, int], ...]:
    """The address ranges the game runs RAM in (EWRAM 0x02000000..0x02040000, IWRAM 0x03000000..
    0x03008000, palette 0x05000000..0x05000400, VRAM 0x06000000..0x06018000, OAM 0x07000000..
    0x07000400, SRAM 0x0E000000..0x0E008000). Functions are in ROM (0x08000000..0x0A000000) or
    BIOS (0x00000000..0x00004000); both are skipped here."""
    return ((0x02000000, 0x02040000), (0x03000000, 0x03008000),
            (0x05000000, 0x05000400), (0x06000000, 0x06018000),
            (0x07000000, 0x07000400), (0x0E000000, 0x0E008000))


def _which_section(address: int, sections: Sequence[tuple[int, int]]) -> tuple[int, int] | None:
    for start, end in sections:
        if start <= address < end:
            return start, end
    return None


def _symbol_end(name: str, address: int, syms: dict[str, int]) -> int | None:
    """End of the RAM symbol: next symbol at or above ADDRESS plus something small, or the
    section's end (a symbol's bytes can spill to the next named one's start). IWRAM/EWRAM
    entries are typically small (a struct field or a buffer), so an arbitrary 0x100 cap fits
    the common case without overlapping into adjacent objects."""
    section_end = _which_section(address, _ram_sections())
    if section_end is None:
        return None
    section_start, section_high = section_end
    next_address = min((other for other in syms.values() if other > address), default=section_high)
    return min(section_high, next_address)


def region_of(address: int) -> str:
    """The bn6f RAM symbol NAME that contains ADDRESS, or a RAM region name when none does
    (the function wrote a byte that no symbol marks; this is usually a bug in the bn6f asm or
    a runtime-only allocation)."""
    if not (0x02000000 <= address < 0x0E008000):
        return "RAM"        # outside the game's RAM (a write to an I/O address would hit this
                            # only by accident; `io_name` is the right test for that case)
    for start, end, name in _ram_symbols():
        if start <= address < end:
            return name
    return _ram_region_name(address)


def _ram_region_name(address: int) -> str:
    """A bare RAM region name (EWRAM, IWRAM, palette, VRAM, OAM, SRAM) when no bn6f data symbol
    covers the address -- the lifter header has every named byte, but a runaway write past the
    end of an object would land here and is still useful to know about."""
    for start, end, region in SNAP_REGIONS:
        if start <= address < end + start and region != "io":
            return region.upper()
    return "RAM"


def io_name(address: int) -> str | None:
    """An I/O register's friendly name, or None if it's not in the table (`io_writes` does not
    list unknown I/O addresses; the raw 0x040000XX goes into the log when needed)."""
    if not (0x04000000 <= address < 0x04000400):
        return None
    for io_address, name in _IO_KNOWN:
        if io_address == address:
            return name
    # An aligned 32-bit I/O register that is not in `_IO_KNOWN`: a guess (`IO@0xNNNN`) rather
    # than a fake name; the lifter header is the source of truth.
    return f"IO@0x{address:08X}"


def _io_register_start(address: int) -> int:
    """The start address of the I/O register containing ADDRESS (the largest address in
    `_IO_KNOWN` that is `<= ADDRESS`). For a 16-bit register like BG0CNT at 0x04000008,
    this returns 0x04000008 for both 0x04000008 and 0x04000009. For an address with no
    register at or below it, returns ADDRESS & ~1 (16-bit aligned, the natural unit)."""
    if not (0x04000000 <= address < 0x04000400):
        return address
    best = address & ~1
    for io_address, _name in _IO_KNOWN:
        if io_address <= address and io_address > best:
            best = io_address
    return best


def _is_io(address: int) -> bool:
    return 0x04000000 <= address < 0x04000400


# I/O addresses whose snapshot diff cannot be attributed to the function:
#   * write-only registers read back as the last fetched instruction ("open bus"), so the
#     captured entry has open-bus bytes and the exit has different open-bus bytes for the
#     last instruction the function executed -- a real write by the function to these
#     registers is invisible in the snapshot.
#   * counters (VCOUNT, timers) tick during the call.
#   * interrupt flags (IF, IF2) can flip without the function writing.
#   * DMA control registers go to 0 once the DMA finishes, hiding the value the function
#     loaded; SAD/DAD are write-only anyway.
#   * reserved / unmapped I/O addresses (0x04000140+ and 0x04000300+) read as open bus.
#
# Categorisation is per the GBA memory map (gbatek), cross-checked against the entry/exit
# byte patterns we see in `tools/oracle.py`'s diffs: every address listed here shows
# 0x24442444 -> 0xf000f000 (open-bus pattern) on a function that the assembly says does
# not write to it, so dropping the diff is correct.
_IO_VOLATILE: tuple[tuple[int, int], ...] = (
    # VCOUNT (16-bit scanline counter, R/O): one word changes per scanline crossing.
    (0x04000006, 0x02),
    # DISPSTAT flag bits (HBlank/VBlank flags, R/O); bits 2/3/6-7 are R/W but the flag
    # bits flip naturally and dominate the diff. The address is shared with the
    # write-only bits, so the whole 16-bit register is dropped.
    (0x04000004, 0x02),
    # DISPCNT upper 16 bits (0x04000002): unmapped per the GBA memory map; reads back as
    # open bus. The lower 16 bits of the same 32-bit word are DISPCNT (R/W, keep).
    (0x04000002, 0x02),
    # BG scroll registers (BG0-3 HOFS/VOFS, all W only).
    (0x04000010, 0x10),
    # BG affine parameters (BG2/3 X, Y, PA-PD, all W only).
    (0x04000020, 0x20),
    # Window 0/1 Horizontal/Vertical dimensions (all W only).
    (0x04000040, 0x08),
    # MOSAIC (W only) plus the unused 16-bit slot next to it.
    (0x0400004C, 0x04),
    # BLDY (W only). The next 16-bit slot (0x04000056) is unmapped and reads as open bus.
    (0x04000054, 0x04),
    # Sound registers 0x58-0xAF: a mix of write-only registers (NR10-NR44, FIFO_A, FIFO_B)
    # and R/W registers the game rarely writes (SOUNDCNT_L/H/X, SOUNDBIAS). The captured
    # entry has open-bus bytes for any the game hasn't touched, so the diff cannot be
    # distinguished from open-bus noise; drop the whole block.
    (0x04000058, 0x58),
    # DMA 0-3 SAD/DAD (all W only).
    (0x040000B0, 0x08), (0x040000BC, 0x08), (0x040000C8, 0x08), (0x040000D4, 0x08),
    # DMA 0-3 CNT (R/W but the count decrements to 0 once the DMA finishes, and the
    # enable bit clears when the transfer ends -- the value the function wrote is gone
    # by the time the exit snapshot is taken).
    (0x040000B8, 0x04), (0x040000C4, 0x04), (0x040000D0, 0x04), (0x040000DC, 0x04),
    # Reserved I/O 0xE0-0xFF (open bus).
    (0x040000E0, 0x20),
    # Timers 0-3 (counters tick during the call).
    (0x04000100, 0x10),
    # Reserved I/O 0x110-0x11F (open bus; no register is mapped here in the bn6f lifter
    # header, but a stray mGBA read of a neighbouring timer register leaves open-bus bytes
    # at these addresses).
    (0x04000110, 0x10),
    # SIO / key input / IR / gamepad pak registers (volatile: link state, key bits).
    (0x04000120, 0x20),
    # Reserved I/O 0x140-0x1FF (open bus).
    (0x04000140, 0xC0),
    # WAKE_HBL (0x04000204) and WAKE_VBL (0x04000206), each W only. The captured entry
    # has open-bus bytes; the exit has different open-bus bytes; the diff would otherwise
    # misreport a 0x45B7 write as the function's. (The lower 16 bits of the 0x04000200
    # 32-bit word are IE, R/W, kept; that word stays out of the volatile list.)
    (0x04000204, 0x04),
    # WAKE_FLAGS (0x0400020A), W only. Sits in the upper 16 bits of the IME 32-bit word
    # at 0x04000208 -- IME itself (lower 16 bits) is R/W and kept, but byte-level diff +
    # per-byte volatile filter lets us drop WAKE_FLAGS and keep IME writes.
    (0x0400020A, 0x02),
    # IF (interrupt flags flip without the function writing; the function's own IF
    # writes show up as 1-bits in the diff, but other IRQs can fire mid-call too).
    (0x04000202, 0x02),
    # IF2.
    (0x04000212, 0x02),
    # Reserved I/O 0x20C-0x2FF (open bus).
    (0x0400020C, 0xF4),
    # Unmapped I/O 0x300-0x3FF (open bus).
    (0x04000300, 0x100),
)


def _is_io_volatile(address: int) -> bool:
    """True if the I/O write at ADDRESS cannot be attributed to the function: it is a
    write-only register (open bus on read), a counter, an interrupt flag, or an
    unmapped / reserved address whose bytes in the snapshot are open bus. The diff
    would otherwise misreport these as writes the function made."""
    for start, size in _IO_VOLATILE:
        if start <= address < start + size:
            return True
    return False


def _add_io_writes(io_writes: Counter, before: int, after: int, address: int, size: int) -> None:
    """Record the I/O writes implied by one MemoryChange (BEFORE/AFTER/SIZE at ADDRESS).
    Walks the change byte by byte: skips volatile bytes (open-bus noise, not a function
    write), and groups consecutive non-volatile bytes belonging to the same register into
    one IOWrite entry -- so a 16-bit IME write shows up as one row (name=IME,
    address=0x04000208, size=2, value=IME_after) rather than two byte rows, even though
    the diff itself is per-byte. The KEY for the IOWrite dict is (name, address, size,
    value); distinct values across probes show up as separate rows (the matched count is
    how many probes had that same write). The name and address are the register's start
    (e.g. a write to byte 0x04000051 of a 16-bit register at 0x04000050 reports the
    register name and address, not `IO@0x04000051`)."""
    offset = 0
    while offset < size:
        byte_addr = address + offset
        if _is_io_volatile(byte_addr):
            offset += 1
            continue
        start_offset = offset
        reg_start = _io_register_start(byte_addr)
        current_name = io_name(reg_start) or f"IO@0x{reg_start:08X}"
        while offset < size and not _is_io_volatile(address + offset) \
                and _io_register_start(address + offset) == reg_start:
            offset += 1
        group_size = offset - start_offset
        before_val = (before >> (start_offset * 8)) & ((1 << (group_size * 8)) - 1)
        after_val = (after >> (start_offset * 8)) & ((1 << (group_size * 8)) - 1)
        io_writes[(current_name, reg_start, group_size, after_val)] += 1


# ── summarise: fold per-state probes into RuntimeFacts ────────────────

def summarise(function: FunctionName, address: GuestAddress, probes: Sequence[Probe]) -> RuntimeFacts:
    """What the probes show about FUNCTION: distinct inputs/outputs, which input registers the
    function changes, how it changed them, the I/O writes, and how often the recorded routes
    call the function (with coverage normalised to per-1000-frames so a short route and a long
    one compare meaningfully)."""
    register_inputs: dict[str, set[int]] = {f"r{index}": set() for index in range(13)}
    register_inputs["sp"] = set()
    register_outputs: dict[str, set[int]] = {f"r{index}": set() for index in range(13)}
    register_outputs["pc"] = set()
    written: dict[str, set[int]] = {f"r{index}": set() for index in range(13)}     # inputs the function changes
    written_how: dict[str, set[str]] = {f"r{index}": set() for index in range(13)}
    byte_writes: Counter = Counter()
    io_writes: Counter = Counter()
    returned = 0
    for probe in probes:
        if not probe.returned or probe.entry is None or probe.exit is None:
            continue
        returned += 1
        for name, value in register_entries(probe.entry.header):
            if name in register_inputs:
                register_inputs[name].add(value)
        for name, value in register_entries(probe.exit.header):
            if name in register_outputs:
                register_outputs[name].add(value)
        for reg, before, after in probe.register_changes:
            written[reg].add(before)
            written_how[reg].add(_classify_change(register_inputs, reg, before, after))
        for change in probe.memory_changes:
            if _is_io(change.address):
                # The I/O diff is byte-level (see _diff_memory). Walk the change byte by byte:
                # skip volatile / write-only registers (open bus in entry and exit; the
                # difference is the last fetched instruction before/during the call, not a
                # real write), and group the remaining consecutive same-named bytes into
                # one IOWrite entry (so a 16-bit IME write shows as one row, not two byte
                # rows). The volatile filter is the only thing that prevents a pure-RAM
                # function from looking like it touched BG scroll / DMA / sound / reserved
                # I/O -- see the open-bus patterns in tools/mgba_run.c and IO_VOLATILE.
                _add_io_writes(io_writes, change.before, change.after, change.address, change.size)
            else:
                byte_writes[(region_of(change.address), change.address)] += change.size
    memory_writes: list[MemoryRegionWrite] = []
    byte_by_symbol: dict[str, int] = {}
    distinct_by_symbol: dict[str, set[int]] = {}
    for (symbol, _address), count in byte_writes.items():
        byte_by_symbol[symbol] = byte_by_symbol.get(symbol, 0) + count
        distinct_by_symbol.setdefault(symbol, set())
        for probe in probes:
            if probe.returned and probe.exit and probe.entry:
                for change in probe.memory_changes:
                    if _is_io(change.address):
                        # Skip volatile I/O -- they are not real function writes.
                        continue
                    if region_of(change.address) == symbol:
                        distinct_by_symbol[symbol].add(change.after)
    for symbol, total_bytes in sorted(byte_by_symbol.items(), key=lambda kv: -kv[1]):
        memory_writes.append(MemoryRegionWrite(symbol=symbol, address=0, bytes=total_bytes,
                                               distinct_values=len(distinct_by_symbol[symbol])))
    io: list[IOWrite] = []
    for (name, addr, size, value), count in sorted(io_writes.items(), key=lambda kv: (kv[0][1], -kv[1])):
        io.append(IOWrite(name=name, address=addr, size=size, value=value, matched=count))
    register_inputs_lines = _register_lines("inputs", register_inputs)
    register_outputs_lines = _register_lines("outputs", register_outputs)
    registers_written = _written_lines(written, written_how)
    written_patterns = _written_patterns(written_how, written)
    return RuntimeFacts(name=function, address=address, probes=len(probes), returned=returned,
                        register_inputs=register_inputs_lines, register_outputs=register_outputs_lines,
                        registers_written=registers_written, written_patterns=written_patterns,
                        io_writes=tuple(io), memory_writes=tuple(memory_writes),
                        route_coverage=_route_coverage(function))


def _classify_change(register_inputs: dict[str, set[int]], reg: str, before: int, after: int) -> str:
    """How this register was changed across the probes: a constant (the function writes the same
    value every time), a copy of an input register (the new value matches another input in the
    same probe), or just `changed` when neither rule fits. The 'constant' and 'copy' shapes
    are the things a symbols/db entry's `details` line uses to justify its name."""
    samples = register_inputs[reg]
    if after in samples:
        return f"constant=0x{after:08X}" if len({after}) == 1 else "constant (one per call site)"
    return f"changed 0x{before:08X}->0x{after:08X}"


def _register_lines(kind: str, table: dict[str, set[int]]) -> tuple[ToolMessage, ...]:
    """The distinct (register, value) pairs as one line per pair, ordered by register then value."""
    out: list[ToolMessage] = []
    for name in sorted(table, key=lambda n: (n != "pc" and n != "sp" and n != "lr", n)):
        values = sorted(table[name])
        if not values:
            continue
        if len(values) <= 4:
            out.append(ToolMessage(f"{kind} {name} = " + ", ".join(f"0x{v:08X}" for v in values)))
        else:
            shown = ", ".join(f"0x{v:08X}" for v in values[:4])
            out.append(ToolMessage(f"{kind} {name} has {len(values)} distinct values: {shown}, ..."))
    return tuple(out)


def _written_lines(written: dict[str, set[int]], _written_how: dict[str, set[str]]) -> tuple[ToolMessage, ...]:
    """The input registers the function changes, as one line per register, in rN order."""
    out: list[ToolMessage] = []
    for reg in sorted(written, key=lambda n: int(n[1:]) if n.startswith("r") else 999):
        if not written[reg]:
            continue
        out.append(ToolMessage(f"writes {reg}"))
    return tuple(out)


def _written_patterns(written_how: dict[str, set[str]], written: dict[str, set[int]]) -> tuple[ToolMessage, ...]:
    """A compact per-register write-pattern summary. The judge uses it to decide whether the
    pattern matches the name (e.g. 'returns constant X in r0' means the name should say so)."""
    out: list[ToolMessage] = []
    for reg in sorted(written, key=lambda n: int(n[1:]) if n.startswith("r") else 999):
        if not written[reg]:
            continue
        patterns = sorted(written_how[reg])
        if not patterns:
            continue
        out.append(ToolMessage(f"{reg}: " + "; ".join(patterns)))
    return tuple(out)


# ── recorded-route coverage (tools/traces/coverage/*.prof) ───────────

_PROF_CACHE: dict[str, frozenset[int]] | None = None
_TRACE_LEN_CACHE: dict[str, int] | None = None


def _prof_addresses() -> dict[str, frozenset[int]]:
    """Each ROUTE.prof's executed addresses, by route name (caches per process since the files
    are 100+ MB and the run asks once per function)."""
    global _PROF_CACHE
    if _PROF_CACHE is not None:
        return _PROF_CACHE
    _PROF_CACHE = {}
    for prof in (TRACES / "coverage").glob("*.prof"):
        addresses: set[int] = set()
        for line in prof.read_text(errors="replace").splitlines():
            if line.startswith("#") or not line.strip():
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            try:
                addresses.add(int(parts[0], 16))
            except ValueError:
                continue
        _PROF_CACHE[prof.stem] = frozenset(addresses)
    return _PROF_CACHE


def _trace_lengths() -> dict[str, int]:
    """Each recorded route's frame count (tools/traces/*.trace; game-frame columns from the
    header row minus first/last)."""
    global _TRACE_LEN_CACHE
    if _TRACE_LEN_CACHE is not None:
        return _TRACE_LEN_CACHE
    _TRACE_LEN_CACHE = {}
    for trace in TRACES.glob("*.trace"):
        last_frame = 0
        for line in trace.read_text(errors="replace").splitlines():
            if line.startswith("#") or not line.strip():
                continue
            comma = line.find(",")
            if comma < 0:
                continue
            try:
                frame = int(line[:comma])
            except ValueError:
                continue
            if frame > last_frame:
                last_frame = frame
        if last_frame:
            _TRACE_LEN_CACHE[trace.stem] = last_frame
    return _TRACE_LEN_CACHE


def _route_coverage(function: FunctionName) -> tuple[ToolMessage, ...]:
    """The recorded routes that executed this function (calls per route and per 1000 frames so
    short and long routes compare on the same scale)."""
    units = funcindex.lifted_units()
    address = units.get(function)
    address_value = address.lo if address is not None else None
    out: list[ToolMessage] = []
    for route, addresses in sorted(_prof_addresses().items()):
        if address_value is None or (address_value & ~1) not in addresses:
            continue
        count = sum(1 for line in (TRACES / "coverage" / f"{route}.prof").read_text(errors="replace").splitlines()
                    if line.split()[:1] == [f"{address_value:08X}"])
        length = _trace_lengths().get(route, 0)
        per = (count * 1000 // length) if length else 0
        out.append(ToolMessage(f"{route}: {count} calls / {length} frames ({per}/1k)"))
    return tuple(out)


# ── the judge prompt and the verdict parser ───────────────────────────

JUDGE_SYSTEM = ("You verify a function's name from runtime facts about it gathered by replaying "
                "captured calls in the original game. Reply with exactly one JSON object and "
                "nothing else.")
JUDGE_TEMPLATE = """A GBA function named `{name}` lives at 0x{address:08X}.

Its symbols/db summary (what the previous assembly-reading step wrote):
{summary}

The interface the symbols/db entry claims:
{interface}

What the original game did when run from {probes} captured call(s) (of which {returned} returned
within the step budget):
{registers}

Memory writes, grouped by the bn6f RAM symbol that contains them, biggest first:
{memory}

I/O registers the function wrote:
{io}

Recorded-route coverage (calls per route / frames, then per-1000 frames):
{routes}

Blind spots of these facts: only memory and registers whose value CHANGED are listed (a write of
the value already there, and every read, are invisible); write-only hardware registers (BG scroll,
DMA, sound, window, mosaic, ...) read back as junk and are never listed, so an empty I/O list does
NOT contradict a name about display, scrolling, DMA or sound; only a few captured calls were replayed,
so paths they did not take are unseen. Use `contradicts` only when a listed fact positively conflicts
with the name; use `unknown` when the facts simply do not show the named behaviour.

Reply with exactly one JSON object and nothing else:
{{
  "verdict": "consistent" | "contradicts" | "unknown",
  "reason": "what in the facts above backs this verdict (at most three sentences; cite a fact: a register value, a memory address, an I/O register, a route count)"
}}

`consistent` = the facts match what the name/summary/interface predict.
`contradicts` = a fact conflicts (cite it: the asserted meaning and what was observed).
`unknown` = the facts don't settle it (state what's missing)."""


def judge_prompt(facts: RuntimeFacts, summary: ToolMessage, interface: ToolMessage | None) -> str:
    registers = "\n".join(facts.register_inputs + facts.registers_written + facts.written_patterns) \
        or "(no register facts)"
    memory = "\n".join(f"  {write.symbol}: {write.bytes} bytes, {write.distinct_values} distinct value(s)"
                       for write in facts.memory_writes) or "  (none)"
    io = "\n".join(f"  {w.name} = 0x{w.value:08X} ({w.size} bytes, in {w.matched} probe(s))"
                   for w in facts.io_writes) or "  (none)"
    routes = "\n".join(facts.route_coverage) or "  (no recorded routes executed this function)"
    return JUDGE_TEMPLATE.format(name=facts.name, address=facts.address, summary=summary,
                                 interface=interface or "(not stated)", probes=facts.probes,
                                 returned=facts.returned, registers=registers, memory=memory, io=io,
                                 routes=routes)


def parse_judge(reply: str) -> tuple[str, ToolMessage | None]:
    """The judge's reply as (verdict_or_empty, problem_or_None). On success the verdict is
    one of `consistent/contradicts/unknown` and the problem is None; on failure the verdict is
    empty and the problem is what kept us from reading one."""
    match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", reply, re.S)
    candidates = [match[1]] if match else []
    first, last = reply.find("{"), reply.rfind("}")
    if 0 <= first < last:
        candidates.append(reply[first:last + 1])
    for candidate in candidates:
        try:
            loaded = json.loads(candidate)
        except json.JSONDecodeError:
            continue
        if isinstance(loaded, dict):
            verdict = loaded.get("verdict")
            if verdict not in ("consistent", "contradicts", "unknown"):
                return "", ToolMessage(f"verdict {verdict!r} is not consistent/contradicts/unknown")
            reason = loaded.get("reason")
            if not isinstance(reason, str) or not reason.strip():
                return "", ToolMessage("a verdict without a reason")
            return verdict, None
    return "", ToolMessage("the reply held no JSON object")


def _read_reason(reply: str) -> ToolMessage:
    """The reason field from the JSON object in REPLY (parse_judge parsed it successfully; the
    reason is what we want to surface on the verdict)."""
    match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", reply, re.S)
    candidates = [match[1]] if match else []
    first, last = reply.find("{"), reply.rfind("}")
    if 0 <= first < last:
        candidates.append(reply[first:last + 1])
    for candidate in candidates:
        try:
            loaded = json.loads(candidate)
        except json.JSONDecodeError:
            continue
        if isinstance(loaded, dict):
            reason = loaded.get("reason")
            if isinstance(reason, str) and reason.strip():
                return ToolMessage(" ".join(reason.split()))
    return ToolMessage("")


# ── model call (asking the judge) ─────────────────────────────────────

USAGE_LOG = REPO / "tools/convert/usage.jsonl"     # tools/llm.py logs every call here (shared)

_consumed: dict[Path, int] = {}
_spent: dict[tuple[Path, str], int] = {}
_tokens_lock = _ImportLock() if False else __import__("threading").Lock()


def _logged_tokens(tag: str) -> int:
    """Tokens tools/llm.py logged for the call TAG (incremental: the log is read forward)."""
    global _consumed, _spent
    with _tokens_lock:
        path = USAGE_LOG
        try:
            size = path.stat().st_size
        except FileNotFoundError:
            return 0
        start = _consumed.get(path, 0)
        if size > start:
            with path.open("rb") as log:
                log.seek(start)
                text = log.read().decode(errors="replace")
            if not text.endswith("\n"):
                text = f"{text.rpartition(chr(10))[0]}\n" if chr(10) in text else ""
            for line in text.splitlines():
                try:
                    loaded = cast(object, json.loads(line))
                except json.JSONDecodeError:
                    continue
                if not isinstance(loaded, dict):
                    continue
                row = cast(dict[str, object], loaded)
                if row.get("tag") == tag:
                    into, out = row.get("in"), row.get("out")
                    if isinstance(into, int) and isinstance(out, int):
                        _spent[(path, tag)] = into + out
            _consumed[path] = start + len(text.encode())
        return _spent.get((path, tag), 0)


def ask_judge(model: ModelSpec, facts: RuntimeFacts, summary: ToolMessage, interface: ToolMessage | None,
              run_id: str, retry_unnamed: bool = False) -> Verdict:
    """The judge's verdict for one function, or the model's error wrapped. A model reply with
    no JSON object is asked once more with a tight follow-up; the retry is counted."""
    import time as _time
    cached = _cached_verdict(run_id, facts.name)
    if cached is not None:
        return cached
    prompt = judge_prompt(facts, summary, interface)
    started = _time.monotonic()
    problem: ToolMessage | None = None
    reason: ToolMessage = ToolMessage("")
    verdict = ""
    tokens = 0
    retries = 0
    for attempt in range(2):
        tag = f"runtime-evidence {run_id} judge {facts.name} {attempt}"
        try:
            reply = llm.complete(model, prompt, system=JUDGE_SYSTEM, max_tokens=2000, timeout=120, retries=2,
                                 tag=tag, usage_log=str(USAGE_LOG))  # pyright: ignore[reportUnknownMemberType]
        except Exception as error:                                    # noqa: BLE001
            return Verdict(name=facts.name, address=facts.address, verdict="unknown",
                           reason=ToolMessage(""), tokens=0, seconds=0.0,
                           problem=ToolMessage(str(error)[:300]))
        tokens += _logged_tokens(tag)
        verdict, problem = parse_judge(reply)
        if verdict and problem is None:
            reason = _read_reason(reply)
            break
        retries = attempt + 1
        if not reason:
            reason = problem or ToolMessage("no JSON object in the reply")
        prompt = (f"{prompt}\n\nYour previous reply could not be used: {problem}\n"
                  "Reply again with only the JSON object.")
    if not verdict:
        verdict = "unknown"
    out = Verdict(name=facts.name, address=facts.address, verdict=verdict,
                  reason=reason if str(reason).strip() else ToolMessage("no reply"),
                  tokens=tokens, seconds=round(_time.monotonic() - started, 1), problem=problem)
    if not retry_unnamed:
        _keep_verdict(run_id, out)
    return out


# ── contrastive judge (multiple choice; supported/contradicted/inconclusive) ──
#
# A previous version of `ask_judge` was a rubber stamp: over 24 negative-control pairs
# (the runtime facts of function A presented with the (name, summary) of function B),
# it said `consistent` 14 times. The verdict carried no information. The fix was to flip
# the question from "is this name consistent with the facts?" to "pick the candidate that
# fits these facts" -- a multiple-choice question that has to single out the truth among
# distractors or admit it cannot. The old judge is kept (available behind a flag) so a
# future run can compare side by side; the contrastive judge is the default when the
# caller's flag is set.
#
# CALIBRATION (on 60 functions from build-wf-runs/runtime-evidence-20261019-180951/,
# minimax/MiniMax-M3, with the `tools/calib_contrastive.py` script):
#   (a) accuracy picking the true option (5-option question): 20/60 = 33.3%
#       Wilson 95% CI [22.7%, 45.9%]. The CI just barely excludes 20% chance (lower bound
#       22.7%) -- the model's signal is real but weak; "clearly above chance" is generous.
#   (b) false-positive rate (4-decoy question, right answer is 0/none, model picked one at
#       conf >= 0.7): 24/60 = 40.0%. 95% CI [28.6%, 52.6%]. Far from "clearly low".
# Per the calibration rule, the runtime facts are not discriminating enough to deploy the
# contrastive judge by default. The default remains `consistent/contradicts/unknown` (the
# old judge). Operators who want to enable the contrastive judge pass `--contrastive` to
# `wf runtime-evidence`; the data is identical, only the verdict classification changes.

CONTRASTIVE_SYSTEM = ("You identify a GBA function from the runtime facts its calls produced "
                       "in the original game. Reply with exactly one JSON object and nothing "
                       "else.")

CONTRASTIVE_TEMPLATE = """Runtime facts about an UNNAMED function in the GBA game "Mega Man Battle Network 6"
(probes replayed the function from K captured calls in the original game through mGBA):

{facts}

Below are 5 candidate (name, summary) pairs that were written by `wf investigate` for different
functions (this codebase's assembly-reading + cross-check pipeline; it sometimes names
the wrong function). The runtime facts may identify ONE of the candidates uniquely, may be
ambiguous between several, or may not match any. Only pick a candidate if the runtime facts
distinctively match IT and not the others.

{candidates}

Blind spots: only memory and registers whose value CHANGED are listed (a write of the
value already there, and every read, are invisible). Write-only hardware registers (BG
scroll, DMA, sound, window, mosaic, ...) read back as junk and are never listed, so an
empty I/O list does NOT contradict a candidate about display, scrolling, DMA or sound.

Reply with exactly one JSON object:
{{
  "choice": <1..5 if a candidate is the unique match; 0 if none fit or the match is ambiguous>,
  "confidence": <0.0..1.0; reserve high confidence (>= 0.7) for cases where the facts distinguish the chosen candidate from every other option>,
  "reason": "<at most three sentences; cite the runtime fact that picked your answer (a register value, a RAM symbol, an I/O register, a route count)>"
}}
"""


ContrastiveCandidate = NamedTuple("ContrastiveCandidate", (    # pyright: ignore[reportUntypedBaseClass]
    ("label", int), ("name", FunctionName), ("summary", str), ("is_truth", bool)))


def build_contrastive_candidates(true_name: FunctionName, true_summary: str,
                                  pool: frozenset[str], facts: RuntimeFacts,
                                  name_to_summary: Callable[[str], str],
                                  rng: random.Random) -> list[ContrastiveCandidate]:
    """The five options for the contrastive judge's prompt: true_name + four decoys.

    Decoys: 2 "hard" (other investigate-named functions with the same name prefix OR
    whose RAM write set overlaps with the truth's, preferring the latter) and 2 random.
    The shuffle order and which slot the truth lands in are both governed by RNG so a
    re-run is reproducible."""
    true_ram = _ram_symbols_written_by(facts)
    hard: list[str] = []
    others = sorted(pool - {str(true_name)})
    for cand in others:
        if any(_symbol_in(cand, sym) for sym in true_ram):
            if cand not in hard:
                hard.append(cand)
        if len(hard) >= 2:
            break
    if len(hard) < 2:
        prefix = str(true_name).split("_", 1)[0]
        for cand in others:
            if cand in hard or cand == str(true_name):
                continue
            if cand.startswith(prefix + "_") or cand == prefix:
                hard.append(cand)
            if len(hard) >= 2:
                break
    if len(hard) < 2:
        # fall back to a sampling; the pool can be small for some functions.
        rand_pool = [c for c in others if c not in hard]
        rng.shuffle(rand_pool)
        hard.extend(rand_pool[: 2 - len(hard)])
    hard = hard[:2]
    random_pool = [c for c in others if c not in hard]
    rng.shuffle(random_pool)
    decoys = hard + random_pool[: 2]
    all5: list[ContrastiveCandidate] = [
        ContrastiveCandidate(label=0, name=true_name, summary=true_summary, is_truth=True),
    ]
    for d in decoys:
        all5.append(ContrastiveCandidate(label=0, name=FunctionName(d), summary=name_to_summary(d),
                                            is_truth=False))
    labelled: list[ContrastiveCandidate] = []
    for idx, cand in enumerate(all5, start=1):
        labelled.append(ContrastiveCandidate(label=idx, name=cand.name, summary=cand.summary,
                                                is_truth=cand.is_truth))
    rng.shuffle(labelled)
    return labelled


def _ram_symbols_written_by(facts: RuntimeFacts) -> tuple[str, ...]:
    """The bn6f RAM symbols `facts` reports as written by the function. Used to pick hard
    decoys (others that share a RAM symbol with the truth -- the same IWRAM/EWRAM layout
    almost certainly means the same code path)."""
    return tuple(write.symbol for write in facts.memory_writes)


def _symbol_in(name: str, symbol_prefix: str) -> bool:
    """Whether `name` (a function name) has facts reporting a write to `symbol_prefix`.
    In the contrastive-judge prompts we only have the truth's write set; we want decoys
    whose names sound similar to functions known to touch that region. Heuristic match:
    the decoy name appears anywhere in the lifted unit set touching the symbol.

    The fallback heuristic: a name that contains the symbol's tail word (e.g.
    `_AttackVars` in `eAIData1_AttackVars`) is treated as a hard negative. The full version
    would load each decoy's facts; we keep this cheap because the contrastive judge runs
    once per function and we want the prompt construction itself to be free of model calls."""
    if not symbol_prefix:
        return False
    needle = symbol_prefix.split("_")[-1].lower()
    if len(needle) < 4:        # 'e', 'iowram', and other short names are noise
        return False
    return needle in name.lower()


def contrastive_judge_prompt(facts: RuntimeFacts, candidates: Sequence[ContrastiveCandidate]) -> str:
    """The model sees the runtime facts and the 5 (label, name, summary) candidates; it does
    NOT see the truth label, just the candidates. The `(function-name) -> SymbolName`
    mapping is the candidate's `(name, summary)` and not the truth's; the judge cannot
    cheat by string-matching "what function is this?"."""
    facts_text = _runtime_facts_text(facts)
    cand_text = "\n".join(f"[{c.label}] name: `{c.name}`\n    summary: {c.summary or '(none)'}"
                            for c in candidates)
    return CONTRASTIVE_TEMPLATE.format(facts=facts_text or "(no facts)", candidates=cand_text)


def parse_contrastive(reply: str) -> tuple[int, float, str, ToolMessage | None]:
    """A `{"choice": int, "confidence": float, "reason": str}` JSON object. Returns
    `(choice, confidence, reason, problem)` -- choice is 0 by default if missing, the
    problem is `None` on a clean parse."""
    match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", reply, re.S)
    candidates_list = [match[1]] if match else []
    first, last = reply.find("{"), reply.rfind("}")
    if 0 <= first < last:
        candidates_list.append(reply[first:last + 1])
    for candidate in candidates_list:
        try:
            loaded = json.loads(candidate)
        except json.JSONDecodeError:
            continue
        if isinstance(loaded, dict):
            choice_raw = loaded.get("choice")
            conf_raw = loaded.get("confidence")
            reason_raw = loaded.get("reason")
            # bool is a subclass of int in Python; reject booleans explicitly so `True` does
            # not become choice 1 / confidence 1.0 silently (a model that returns
            # `"choice": true` would otherwise look like it picked candidate 1 with full
            # confidence).
            if (not isinstance(choice_raw, int) or isinstance(choice_raw, bool)
                    or not isinstance(conf_raw, (int, float)) or isinstance(conf_raw, bool)):
                continue
            choice = choice_raw
            conf = max(0.0, min(1.0, float(conf_raw)))
            reason = str(reason_raw or "").strip()
            if not reason:
                return choice, conf, "", ToolMessage("a verdict without a reason")
            return choice, conf, reason, None
    return 0, 0.0, "", ToolMessage("the reply held no JSON object")


CONTRASTIVE_CONFIDENCE = 0.7     # the threshold the brief uses for a confident contradicting pick


def ask_contrastive_judge(model: ModelSpec, facts: RuntimeFacts,
                            candidates: Sequence[ContrastiveCandidate], run_id: str,
                            confidence_threshold: float = CONTRASTIVE_CONFIDENCE) -> Verdict:
    """Run the contrastive judge on one function and fold the JSON reply into a verdict.

    Mapping (per the brief):
      choice == truth's label    -> verdict = "supported"
      choice in [1..5] and conf >= threshold and not truth -> verdict = "contradicted"
      otherwise (choice 0 / low confidence / unparsed) -> verdict = "inconclusive"

    Calibration (60 functions from build-wf-runs/runtime-evidence-20261019-180951/, see
    tools/calib_contrastive.py; minimax/MiniMax-M3; 5-option question with 1 truth + 4 decoys;
    4-decoy question with the truth removed):
      (a) accuracy picking the true option (5-option): 20/60 = 33.3%
          Wilson 95% CI [22.7%, 45.9%]. The CI just barely excludes 20% chance
          (lower bound is 22.7%) -- the model's signal is real but weak.
      (b) false-positive rate (truth removed, picked at conf >= 0.7): 24/60 = 40.0%
          Wilson 95% CI [28.6%, 52.6%]. Far from "clearly low".
    Per the brief's calibration rule (both bars must be clearly cleared), the runtime facts
    are not discriminating enough to deploy the contrastive judge by default. The default
    stays `consistent/contradicts/unknown` (the old judge). Operators who want to enable the
    contrastive judge pass `--contrastive`; the data is identical, only the verdict
    classification changes. Per the brief, we do NOT tune on this evaluation set."""
    import time as _time
    started = _time.monotonic()
    prompt = contrastive_judge_prompt(facts, candidates)
    truth_label = next((c.label for c in candidates if c.is_truth), 0)
    tokens = 0
    choice, confidence, reason = 0, 0.0, ""
    problem: ToolMessage | None = None
    for attempt in range(2):
        tag = f"runtime-evidence {run_id} contrastive {facts.name} {attempt}"
        try:
            reply = llm.complete(model, prompt, system=CONTRASTIVE_SYSTEM, max_tokens=600,
                                    timeout=120, retries=2, tag=tag, usage_log=str(USAGE_LOG))
        except Exception as error:                                # noqa: BLE001
            return Verdict(name=facts.name, address=facts.address, verdict="inconclusive",
                            reason=ToolMessage(""), tokens=0, seconds=0.0,
                            problem=ToolMessage(str(error)[:300]))
        tokens += _logged_tokens(tag)
        choice, confidence, reason, problem = parse_contrastive(reply)
        if problem is None and reason:
            break
        prompt = (f"{prompt}\n\nYour previous reply could not be used: {problem}\n"
                    "Reply again with only the JSON object.")
    if choice == truth_label:
        verdict = "supported"
    elif 1 <= choice <= len(candidates) and confidence >= confidence_threshold:
        verdict = "contradicted"
    else:
        verdict = "inconclusive"
    chosen = next((c for c in candidates if c.label == choice), None)
    reason_text = (f"picked [{choice}] `{chosen.name}` at confidence {confidence:.2f}: "
                    f"{reason}") if (chosen and choice != 0) else (reason or "(no reason)")
    return Verdict(name=facts.name, address=facts.address, verdict=verdict,
                    reason=ToolMessage(reason_text), tokens=tokens,
                    seconds=round(_time.monotonic() - started, 1), problem=problem)



def _verdict_dir(run_id: str) -> Path:
    """A run's verdicts folder (one JSON per function)."""
    return RUNTIME / run_id / "verdicts"


def _cached_verdict(run_id: str, name: FunctionName) -> Verdict | None:
    path = _verdict_dir(run_id) / f"{name}.json"
    if not path.exists():
        return None
    try:
        return Verdict.model_validate_json(path.read_text())
    except ValueError:
        return None


def _keep_verdict(run_id: str, verdict: Verdict) -> None:
    folder = _verdict_dir(run_id)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"{verdict.name}.json").write_text(verdict.model_dump_json())



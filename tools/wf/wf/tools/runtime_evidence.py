# ── snapshot format (tools/mgba_run.c `save_snapshot_named`) ─────────

SNAP_HEADER_WORDS = 19                            # r0..r14 + pc + cpsr (+ the magic + version)
SNAP_HEADER_BYTES = SNAP_HEADER_WORDS * 4

# EWRAM, IWRAM, I/O, palette, VRAM, OAM, SRAM (saved in that order after the header).
SNAP_REGIONS: tuple[tuple[int, int, str], ...] = (
    (0x02000000, 0x40000, "ewram"),
    (0x03000000, 0x8000,  "iwram"),
    (0x04000000, 0x400,   "io"),
    (0x05000000, 0x400,   "pal"),
    (0x06000000, 0x18000, "vram"),
    (0x07000000, 0x400,   "oam"),
    (0x0E000000, 0x8000,  "sram"),
)
SNAP_MEMORY_BYTES = sum(size for _base, size, _name in SNAP_REGIONS)


# ── results ───────────────────────────────────────────────────────────

class Snap(Result):
    """One mGBA snapshot's header and memory (tools/mgba_run saves the headers in words 0..18;
    word 0 is the magic "BN6S", word 1 the format version, words 2..16 are r0..r14, 17 is PC,
    18 is CPSR; the memory is concatenated region by region in SNAP_REGIONS)."""
    header: tuple[int, ...]
    memory: bytes
    path: Path


class MemoryChange(Result):
    """One 32-bit word that changed between entry and exit: address, size in bytes, before, after."""
    address: GuestAddress
    size: int
    before: int
    after: int


class Probe(Result):
    """One entry state's run through the original: did it return (LR reached), what did the
    registers and memory look like at the exit snapshot the original produced."""
    returned: bool
    cycles: int | None = None            # not reported by tools/mgba_run as of this writing
    instructions: int | None = None      # same
    entry: Snap | None = None
    exit: Snap | None = None
    exit_pc: GuestAddress | None = None   # last PC the original had (== entry's LR on a clean return)
    register_changes: tuple[tuple[str, int, int], ...] = ()  # (reg, before, after) for r0..r12
    memory_changes: tuple[MemoryChange, ...] = ()
    problem: ToolMessage | None = None    # mgba_run missing, timeout, did not return, ...


class IOWrite(Result):
    """One write to the I/O region (0x04000000-0x04000400): the register's friendly name, the size
    of the original's store (1/2/4 bytes), and the value the original wrote there."""
    name: SymbolName
    address: GuestAddress
    size: int
    value: int
    matched: int = 0                     # how many of the function's probes did this same write


class MemoryRegionWrite(Result):
    """Writes the function made, grouped by the bn6f RAM symbol that contains them (or just an
    IWRAM/EWRAM base if no symbol covers the bytes; an I/O write has its own IOWrite)."""
    symbol: SymbolName                   # a friendly name, e.g. "oBattleState_BattleSettings" or "IWRAM"
    address: GuestAddress                # the first byte written in this symbol
    bytes: int                           # how many bytes the function wrote inside it
    distinct_values: int                 # how many distinct values across probes


class RuntimeFacts(Result):
    """What the probes show about one function: registers, RAM it touches, I/O it touches, and
    how its current name's predicted use shows up in the recorded routes (calls per route and
    per 1000 frames of those routes)."""
    name: FunctionName
    address: GuestAddress
    probes: int
    returned: int                          # of the probes, how many returned
    register_inputs: tuple[ToolMessage, ...]   # distinct (reg, value) seen across the entry states
    register_outputs: tuple[ToolMessage, ...]  # distinct (reg, value) seen across the exits
    registers_written: tuple[ToolMessage, ...]  # which input registers the function changes
    written_patterns: tuple[ToolMessage, ...]   # the writes it makes (constant, copy of arg, ...)
    io_writes: tuple[IOWrite, ...]
    memory_writes: tuple[MemoryRegionWrite, ...]
    route_coverage: tuple[ToolMessage, ...]   # route: calls / 1000 frames of that route


class Verdict(Result):
    """The judge's reply for one function, with the reason the model gave for its verdict."""
    name: FunctionName
    address: GuestAddress
    verdict: str                          # "consistent" | "contradicts" | "unknown"
    reason: ToolMessage
    tokens: int
    seconds: float
    problem: ToolMessage | None = None    # never reachable: HTTP 402, straggler, ...



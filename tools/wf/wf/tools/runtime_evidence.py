# ── snapshots: parsing ───────────────────────────────────────────────

def parse_snap(path: Path) -> Snap:
    """An mGBA snapshot file. The 76-byte header carries 19 little-endian words (magic "BN6S",
    version, r0..r14, PC, CPSR); the remaining SNAP_MEMORY_BYTES bytes are the saved memory
    (EWRAM, IWRAM, I/O, palette, VRAM, OAM, SRAM, in that order)."""
    data = path.read_bytes()
    if len(data) < SNAP_HEADER_BYTES + SNAP_MEMORY_BYTES:
        raise ValueError(f"{path} is {len(data)} bytes; a snapshot is at least "
                         f"{SNAP_HEADER_BYTES + SNAP_MEMORY_BYTES}")
    header = struct.unpack("<19I", data[:SNAP_HEADER_BYTES])
    if header[0] != 0x53364E42:
        raise ValueError(f"{path}: magic {header[0]:#x} != 0x53364E42 ('BN6S')")
    return Snap(header=tuple(header), memory=bytes(data[SNAP_HEADER_BYTES:SNAP_HEADER_BYTES + SNAP_MEMORY_BYTES]),
                path=path)


def _register(header: tuple[int, ...], name: str) -> int:
    """A register's value as it sits in the header (r0..r14 at header[2..16])."""
    if name == "pc":
        return header[17]
    if name == "cpsr":
        return header[18]
    if name == "sp":
        return header[2 + 13]
    if name == "lr":
        return header[2 + 14]
    index = int(name[1:])
    if 0 <= index <= 12:
        return header[2 + index]
    raise ValueError(name)


def register_entries(header: tuple[int, ...]) -> tuple[tuple[str, int], ...]:
    """The snapshot's registers as (name, value) pairs in r0..r12, SP, LR, PC order (CPSR is a
    flag word, not a register; the runtime facts do not report it as a register)."""
    out: list[tuple[str, int]] = []
    for index in range(13):
        out.append((f"r{index}", header[2 + index]))
    out.append(("sp", header[2 + 13]))
    out.append(("lr", header[2 + 14]))
    out.append(("pc", header[17]))
    return tuple(out)


# ── entry states: building ───────────────────────────────────────────

def _captured_snaps(function: FunctionName) -> tuple[Path, ...]:
    """The function's captured calls' entry snapshots, sorted newest first (newest capture run
    first is the task's preference for "newest first" within a function; the entries are from
    `wf investigate` runs, so the date stamps across functions vary widely)."""
    folder = SNAPSHOTS / function
    if not folder.is_dir():
        return ()
    return tuple(sorted((path for path in folder.glob("*.bin")
                         if not path.name.endswith(".exit.bin")),
                        key=lambda path: path.stat().st_mtime, reverse=True))


def _captured_exits(function: FunctionName) -> tuple[Path, ...]:
    """The captured exits for the function (the originals the probe would re-run from the same
    inputs): most captured calls still have their exit, and the probe's run uses it as the
    reference for whether the rebuilt state converges to the same place the original game did."""
    folder = SNAPSHOTS / function
    if not folder.is_dir():
        return ()
    return tuple(path for path in folder.glob("*.exit.bin"))


def _entry_state(function: FunctionName, count: int) -> tuple[Snap, ...]:
    """K entry states for the function, taken from its captured calls (newest first)."""
    bases, _ = _load_capture_bases(function)
    if not bases:
        return ()
    return tuple(bases[i % len(bases)] for i in range(count))    # wrap if not enough captured


def _load_capture_bases(function: FunctionName) -> tuple[Snap, ...]:
    """The snapshots under `build-snapshots/NAME/snap_*.bin` (the entry states the game's real
    calls produced; sorted newest first). Captured exits are paired up to the same index so
    `probe_state` can compare the rebuilt run's exit against the game's own exit."""
    paths = _captured_snaps(function)
    if not paths:
        return ()
    return tuple(parse_snap(path) for path in paths)


def find_mgba_run() -> Path:
    """Where the project keeps the mGBA runner (tools/oracle.py invokes it the same way)."""
    path = PROJECT_ROOT_BIN
    if not path.exists():
        raise FileNotFoundError(f"mgba_run not found at {path}; build it with tools/build.sh first")
    return path


def _io_snapshot_offset() -> int:
    """Byte offset of the I/O region within an mGBA snapshot's memory: EWRAM (0x40000 bytes)
    + IWRAM (0x8000 bytes) come first, then I/O."""
    return 0x40000 + 0x8000


def _io_template() -> bytes:
    """What mGBA's I/O registers 0x04000058-0x040003FF read back after --call-snaps loads a
    snapshot: the display registers (below 0x58) come from the snapshot; everything else
    takes mGBA's defaults. Run nullsub (a `mov pc, lr`) once with the captured memory and
    read the I/O bytes its exit snapshot has, so the entry we hand mgba_run has the same
    I/O state on the host as the one the function will see when the emulator loads the
    snapshot.

    The exit snapshot's I/O bytes are the values mGBA returns when --call-snaps loads a
    snapshot and immediately runs a no-op: IE/IF/IME are 0 (mGBA's loader forces them),
    and every other register is whatever mGBA defaults to after a clean boot. Without
    this rewrite, the diff at IE/IME/WAITCNT/sound/timers/etc. is the `loaded-snapshot`
    clear, not the function's writes.

    The trick: PC points at nullsub_58 (0x0801BFEC), LR points at MAGIC_LR (0x080000C1,
    ROM header byte 0, never executed). nullsub does `mov pc, lr`; the return check is
    PC == entry LR (with the Thumb bit stripped), so the function "returns" to a never-
    executed word of ROM and the run finishes without doing anything else. The exit
    snapshot's I/O bytes are exactly what mGBA sees after a clean load."""
    import gamepaths  # noqa: PLC0415
    import tempfile
    magic_lr = 0x080000C1        # a word in the ROM header that the game never executes
    with tempfile.TemporaryDirectory() as temp:
        snap_path = Path(temp) / "snap_io_template_0.bin"
        # Header: PC = nullsub_58 (so the loaded snapshot executes one Thumb instruction),
        # LR = MAGIC_LR (so nullsub's `mov pc, lr` "returns" to a never-executed word).
        # Registers r0-r12 / SP / CPSR are zero (mGBA's defaults).
        header = struct.pack("<19I", 0x53364E42, 1, *[0] * 13, 0x03007FE0, magic_lr,
                             0x0801BFEC, 0x9F | 0x20)
        snap_path.write_bytes(header + bytes(SNAP_MEMORY_BYTES))
        subprocess.run([str(find_mgba_run()), str(_game_rom()), "--quiet",
                        "--frames", "1", "--bios", _game_bios(),
                        "--call-snaps", str(temp), "1000"], capture_output=True, check=False,
                       timeout=PROBE_TIMEOUT)
        exit_path = Path(temp) / "snap_io_template_0.exit.bin"
        if not exit_path.exists():
            return bytes(0x400 - 0x58)        # worst case: zero-fill
        exit_data = exit_path.read_bytes()
        off = SNAP_HEADER_BYTES + _io_snapshot_offset() + 0x58
        return exit_data[off:off + (0x400 - 0x58)]


def _rewrite_entry_io(snap: Snap, io_template: bytes) -> Snap:
    """The entry snapshot with its I/O bytes replaced so that the diff against the exit
    snapshot reflects what the function actually wrote. Follows tools/oracle.py:

      * display registers (0x04000000-0x04000057): kept as captured (mgba_run's
        --call-snaps loads these verbatim; they are the only I/O the snapshot controls)
      * interrupts (IE 0x04000200, IF 0x04000202, IME 0x04000208): zeroed (mgba_run
        hard-codes these to 0 so an IRQ cannot fire during the call)
      * non-display I/O (0x04000058-0x040003FF): replaced with the values mGBA reads
        back after loading a snapshot (sound / timers / DMA / SIO / key input /
        unmapped -- whatever mGBA defaults those registers to)
      * write-only display registers (BG scroll 0x04000010-0x04000047, MOSAIC
        0x0400004C-0x0400004D, BLDY 0x04000054-0x04000055): zeroed (they read back
        as open bus on the GBA, which mGBA's loader does not try to populate)

    Without this rewrite, the diff shows every I/O register as "written by the
    function" when mGBA's loader is what changed them between entry and exit."""
    memory = bytearray(snap.memory)
    io_off = _io_snapshot_offset()
    # 1) Display registers 0x00-0x57 stay as captured.
    # 2) Write-only display regs (BG scroll 0x10-0x47, MOSAIC 0x4C, BLDY 0x54): zero.
    for lo, hi in ((0x10, 0x48), (0x4C, 0x50), (0x54, 0x58)):
        for byte_index in range(lo, hi):
            memory[io_off + byte_index] = 0
    # 3) Non-display I/O (0x58-0x3FF): the values mGBA reads after a snapshot load.
    end_off = io_off + 0x400
    start_off = io_off + 0x58
    if len(io_template) == end_off - start_off:
        memory[start_off:end_off] = io_template
    # 4) Interrupts: IE 0x200, IF 0x202, IME 0x208 forced to 0.
    for byte_index in (0x200, 0x201, 0x202, 0x203, 0x208, 0x209):
        memory[io_off + byte_index] = 0
    return Snap(header=snap.header, memory=bytes(memory), path=snap.path)


def run_original(function: FunctionName, states: int, run_id: str, work_dir: Path) -> tuple[Probe, ...]:
    """Run the function in the original game from `states` entry states and save each exit
    snapshot next to its entry (mgba_run --call-snaps writes the .exit.bin in the same dir).
    The mgba_run call is the one tools/oracle.py uses (--call-snaps); loading from an entry
    snapshot, stepping until PC == LR & SP matches, saving the exit. Per state: a Probe with
    the exit snapshot's header and the memory diff between entry and exit.

    The entry snapshot's I/O bytes are rewritten so the I/O region in the diff is the
    function's writes only (see `_rewrite_entry_io`). The captured entry has whatever I/O
    bytes the game had when it produced the snapshot -- those are not what mGBA's
    --call-snaps loads, so diffing them against the exit reports every I/O register as
    a write by the function. tools/oracle.py works around this by pre-rewriting the
    entry snapshot's I/O bytes to what mGBA will see; we do the same."""
    bases = _load_capture_bases(function)
    if not bases:
        return ()
    work_dir.mkdir(parents=True, exist_ok=True)
    (work_dir / "entries").mkdir(exist_ok=True)
    io_template = _io_template()
    chosen = tuple(bases[i % len(bases)] for i in range(states))
    for index, snap in enumerate(chosen):
        # Rewrite the entry's I/O region so the diff against the exit is the function's
        # writes, not the snapshot-loader state (see _rewrite_entry_io for the byte map).
        rewritten = _rewrite_entry_io(snap, io_template)
        (work_dir / "entries" / f"snap_{function}_{index:03d}.bin").write_bytes(
            struct.pack("<19I", *rewritten.header) + rewritten.memory)
    mgba_run = find_mgba_run()
    rom = _game_rom()
    try:
        done = subprocess.run([str(mgba_run), str(rom), "--quiet",
                               "--frames", "1", "--bios", _game_bios(),
                               "--call-snaps", str(work_dir / "entries"), str(PROBE_TIMEOUT * 200)],
                              capture_output=True, text=True, check=False, timeout=PROBE_TIMEOUT)
    except (FileNotFoundError, subprocess.TimeoutExpired) as error:
        return tuple(_missed(function, index, f"mgba_run failed: {error}") for index in range(states))
    if not (work_dir / "entries").exists():       # mgba_run treated --call-snaps as missing
        return tuple(_missed(function, index, "mgba_run did not run --call-snaps on the entries")
                     for index in range(states))
    probes: list[Probe] = []
    for index in range(states):
        entry_path = work_dir / "entries" / f"snap_{function}_{index:03d}.bin"
        exit_path = work_dir / "entries" / f"snap_{function}_{index:03d}.exit.bin"
        if not exit_path.exists():
            probes.append(_missed(function, index, "mgba_run did not return this call within "
                                                    f"{PROBE_TIMEOUT * 200} steps")[0])
            continue
        entry = parse_snap(entry_path)
        exit_snap = parse_snap(exit_path)
        probes.append(_probe_from_exit(entry, exit_snap))
    return tuple(probes)


def _missed(function: FunctionName, index: int, reason: str) -> tuple[Probe, ...]:
    """An exit-less probe (mgba_run missing, did not return, run aborted)."""
    return (Probe(returned=False, problem=ToolMessage(reason),
                  entry=Snap(header=(0,) * SNAP_HEADER_WORDS, memory=b"", path=Path(""))
                  if False else None),)        # no entry parsed; the caller doesn't need one for a miss


def _probe_from_exit(entry: Snap, exit_snap: Snap) -> Probe:
    """A probe whose exit is the original's last PC/registers/memory at the function's return
    (PC == entry.LR & SP == entry.SP; if not, the original did not return cleanly)."""
    entry_lr = entry.header[2 + 14]
    entry_sp = entry.header[2 + 13]
    returned = (((exit_snap.header[17] & ~1) == (entry_lr & ~1))
                and exit_snap.header[2 + 13] == entry_sp)
    register_changes: list[tuple[str, int, int]] = []
    for index in range(13):
        before, after = entry.header[2 + index], exit_snap.header[2 + index]
        if before != after:
            register_changes.append((f"r{index}", before, after))
    diffs = _diff_memory(entry.memory, exit_snap.memory)
    return Probe(returned=returned, entry=entry, exit=exit_snap, exit_pc=GuestAddress(exit_snap.header[17]),
                 register_changes=tuple(register_changes), memory_changes=diffs)


def _diff_memory(before: bytes, after: bytes) -> tuple[MemoryChange, ...]:
    """The bytes that differ between BEFORE and AFTER. RAM regions (EWRAM, IWRAM, palette,
    VRAM, OAM, SRAM) use 32-bit aligned diffs (size=4); the I/O region (0x04000000..) uses
    byte-level diffs so volatile / write-only registers can be filtered individually -- the
    0x04000208 word, e.g., carries IME (R/W, keep) in its lower 16 bits and WAKE_FLAGS
    (W-only, open-bus, drop) in its upper 16 bits; a word-level diff would misreport the
    IME write as touching WAKE_FLAGS too. See the open-bus patterns in tools/mgba_run.c
    and IO_VOLATILE in this file for the source of the noise.

    The I/O diff is bounded by the snapshot's I/O region (1024 bytes); the rest is the
    snapshot's RAM regions (large size * 0x40000 etc.). Each byte-level run of consecutive
    changed bytes becomes one MemoryChange (size=1..1024)."""
    length = min(len(before), len(after))
    out: list[MemoryChange] = []
    io_start = 0x40000 + 0x8000                    # I/O region starts after EWRAM+IWRAM
    io_end = io_start + 0x400                      # the I/O region is 0x400 bytes
    # RAM regions below the I/O region: 32-bit aligned diff (size=4).
    for offset in range(0, min(length, io_start), 4):
        before_word = struct.unpack_from("<I", before, offset)[0]
        after_word = struct.unpack_from("<I", after, offset)[0]
        if before_word != after_word:
            out.append(MemoryChange(address=GuestAddress(_offset_to_address(offset)),
                                    size=4, before=before_word, after=after_word))
    # I/O region: byte-level diff. Each run of consecutive changed bytes is one MemoryChange;
    # the volatile filter in summarise() then drops the open-bus bytes individually.
    offset = min(length, io_start)
    io_end = min(io_end, length)
    while offset < io_end:
        if before[offset] == after[offset]:
            offset += 1
            continue
        start = offset
        while offset < io_end and before[offset] != after[offset]:
            offset += 1
        size = offset - start
        before_val = int.from_bytes(before[start:offset], 'little')
        after_val = int.from_bytes(after[start:offset], 'little')
        out.append(MemoryChange(address=GuestAddress(_offset_to_address(start)),
                                size=size, before=before_val, after=after_val))
    # RAM regions above the I/O region: 32-bit aligned diff (size=4).
    for offset in range(max(io_end, io_start + 0x400) & ~3, length, 4):
        before_word = struct.unpack_from("<I", before, offset)[0]
        after_word = struct.unpack_from("<I", after, offset)[0]
        if before_word != after_word:
            out.append(MemoryChange(address=GuestAddress(_offset_to_address(offset)),
                                    size=4, before=before_word, after=after_word))
    return tuple(out)


def _offset_to_address(offset: int) -> int:
    """The guest address the byte OFFSET in the snapshot's memory corresponds to (the mGBA
    snapshot concatenates the regions in SNAP_REGIONS order)."""
    cumulative = 0
    for base, size, _name in SNAP_REGIONS:
        if offset < cumulative + size:
            return base + (offset - cumulative)
        cumulative += size
    raise ValueError(f"snapshot memory offset {offset} exceeds the saved regions")



"""Runtime evidence for the symbols/db entries that `wf investigate` produced: build K entry
states from a function's captured calls, run each state through the original game in mGBA to the
function's return, summarise what the function actually did (registers in/out, memory it changed
grouped by the bn6f RAM symbol that contains them, I/O register writes), and ask a model whether
those facts are consistent with the current name and summary.

The workflow lives in `tools/wf/wf/graphs/runtime_evidence.py`; this file holds its pure parts:

  - parse_snap(path)              the binary header + memory of a tools/mgba_run --snap snapshot
  - build_entry_states(...)       K entry states from the function's captured calls, deterministic
  - run_original(...)             build-tools/mgba_run --call-snaps on those states, parse the exits
  - diff_memory(...)              the 32-bit words that changed and their (before, after) values
  - region_of(address)            the named bn6f RAM symbol that contains the address (or "RAM")
  - io_name(address)              an I/O register's friendly name (DISPCNT, BG0CNT, DMA3CNT, ...)
  - summarise(probes)             the RuntimeFacts block: distinct inputs/outputs, write patterns,
                                  I/O touched, and per-route / per-1000-frames coverage from the
                                  .prof counts and trace lengths (tools/traces)
  - judge_prompt(...) / parse_judge(...)
                                  the model's prompt and the consistent/contradicts/unknown reply
  - make_evidence_item(...)       the symbols/db evidence item the run writes under
                                  build/runtime/RUN_ID/NAME.yaml

The output of `run_original` is a `Probe` per (function, state), which `summarise` folds into
`RuntimeFacts`. Nothing here touches bn6f, symbols/db, or git: the human reviews the YAML files
under build/runtime/RUN_ID/ and only then `wf record` lands them."""
